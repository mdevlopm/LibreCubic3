#!/usr/bin/env python3
"""Regenerate kobra_screen/font_metrics.py from fonts/AlibabaSans-Regular.ttf.

The printer draws text with LVGL TinyTTF from this very file (same md5 as
/useremain/rinkhals/.current/opt/rinkhals/ui/assets/AlibabaSans-Regular.ttf), so measuring
the TTF here gives the widths the printer will use.  Needs Pillow; the app itself does not.

    python3 gen_font_metrics.py
"""

import hashlib
import os
import struct

from PIL import ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.join(HERE, "fonts", "AlibabaSans-Regular.ttf")
OUT = os.path.join(HERE, "kobra_screen", "font_metrics.py")

# Latin (incl. Turkish), general punctuation, arrows and the few symbols the UI uses.
RANGES = ((0x20, 0x7E), (0xA0, 0x17F), (0x2010, 0x2027), (0x2030, 0x203A), (0x2190, 0x2193), (0x2713, 0x2713),
          (0x00D7, 0x00D7))


def table_info(data):
    count = struct.unpack(">H", data[4:6])[0]
    tabs = {}
    for i in range(count):
        tag, _, off, length = struct.unpack(">4sIII", data[12 + 16 * i:28 + 16 * i])
        tabs[tag.decode()] = (off, length)
    off = tabs["head"][0]
    upem = struct.unpack(">H", data[off + 18:off + 20])[0]
    off = tabs["hhea"][0]
    ascent, descent, gap = struct.unpack(">hhh", data[off + 4:off + 10])
    return upem, ascent, descent, gap


def main():
    data = open(FONT, "rb").read()
    upem, ascent, descent, gap = table_info(data)
    # Basic layout = no GPOS kerning, like stb_truetype in LVGL TinyTTF.
    big = ImageFont.truetype(FONT, upem, layout_engine=ImageFont.Layout.BASIC)
    widths = {}
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            ch = chr(cp)
            units = int(round(big.getlength(ch)))
            if units > 0 or ch == " ":
                widths[ch] = units
    lines = [
        '"""Advance widths of AlibabaSans-Regular.ttf in font units (generated by gen_font_metrics.py; do not edit).',
        "",
        "Source font md5: %s" % hashlib.md5(data).hexdigest(),
        '"""',
        "",
        "UNITS_PER_EM = %d" % upem,
        "ASCENT = %d" % ascent,
        "DESCENT = %d" % descent,
        "LINE_GAP = %d" % gap,
        "DEFAULT_ADVANCE = %d  # unknown glyphs" % int(round(upem * 0.6)),
        "",
        "ADVANCES = {",
    ]
    row = "   "
    for ch, units in sorted(widths.items()):
        item = " %r: %d," % (ch, units)
        if len(row) + len(item) > 118:
            lines.append(row)
            row = "   "
        row += item
    lines.append(row)
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("%s: %d glyphs" % (OUT, len(widths)))


if __name__ == "__main__":
    main()
