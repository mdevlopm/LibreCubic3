@dataclass
class Placed:
    x: int
    y: int
    w: int
    h: int
    widget: object


def place(elements, x, y, w, out, gap=GAP):
    """Lay elements out top to bottom inside width w; returns the y below them."""
    for element in elements:
        if isinstance(element, Rule):
            out.append(Placed(x, y, w, 1, element))
            y += 1 + gap
            continue
        if isinstance(element, Card):
            slot = len(out)
            out.append(None)
            pad = element.pad
            bottom = place(element.rows, x + pad, y + pad, w - 2 * pad, out, gap=element.gap) - element.gap + pad
            border_width = 2 if element.border == "danger_border" else 1
            out[slot] = Placed(x, y, w, bottom - y, Panel(
                element.color, element.border, element.radius, border_width, element.action))
            y = bottom + gap
            continue
        total = sum(widget.weight for widget in element.widgets)
        usable = w - gap * (len(element.widgets) - 1)
        left = float(x)
        for widget in element.widgets:
            width = usable * widget.weight / total
            if isinstance(widget, Col):
                place(widget.rows, round(left), y, round(width), out, gap=widget.gap)
            elif isinstance(widget, Card):
                slot = len(out)
                out.append(None)
                pad = widget.pad
                bottom = place(widget.rows, round(left) + pad, y + pad, round(width) - 2 * pad,
                               out, gap=widget.gap) - widget.gap + pad
                border_width = 2 if widget.border == "danger_border" else 1
                out[slot] = Placed(round(left), y, round(width), max(element.height, bottom - y), Panel(
                    widget.color, widget.border, widget.radius, border_width, widget.action))
            elif not isinstance(widget, Spacer):
                out.append(Placed(round(left), y, round(width), element.height, widget))
            left += width + gap
        y += element.height + gap
    return y


def button_icon_size(item):
    widget = item.widget
    if widget.kind == "estop":
        return "small"
    if widget.kind in ("tab", "tab_active") or (widget.vertical and item.h >= 52):
        return "big"
    if not widget.vertical and widget.text and item.w < 135:
        return "small"
    return "normal"


def button_dot_radius(item):
    widget = item.widget
    limit = 24 if (widget.align == "left" and item.w < 145) else DOT_SIZE
    return min(limit, item.h - 10, item.w - 10) / 2.0


def _left_geometry(item):
    widget = item.widget
    compact_left = item.w < 145
    pad_r = (52 if widget.toggle is not None else 28 if widget.right_icon else 6) if compact_left else (
        56 if widget.toggle is not None else 32 if widget.right_icon else 12)
    left_pad = 8 if compact_left else 14
    gap = 6 if compact_left else 10
    return left_pad, gap, pad_r


def _centered_geometry(item):
    pad_x = 4 if item.w < 72 else (5 if item.w < 120 else 8)
    gap = 4 if item.w < 72 else (5 if item.w < 120 else 8)
    return pad_x, gap


def _visual_width(item):
    widget = item.widget
    return (button_dot_radius(item) * 2.0 if widget.dot is not None
            else (ICON_SIZES[button_icon_size(item)] if widget.icon else 0))


def button_text_size(item):
    """Text size actually drawn for a button label (see `button_label`)."""
    return button_label(item)[0]


def _nominal_size(item):
    """Preferred text size of a button label before `button_label` shrinks it to fit its box."""
    widget = item.widget
    if widget.kind in ("tab", "tab_active"):
        return "tab"
    if widget.kind == "key":
        return "big"
    if widget.kind == "kbd":
        return "small"
    if widget.size:
        return widget.size
    has_visual = bool(widget.icon) or widget.dot is not None
    if widget.align == "left":
        left_pad, gap, pad_r = _left_geometry(item)
        visual = _visual_width(item)
        box_w = max(8.0, item.w - (left_pad + visual + gap if has_visual else left_pad) - pad_r)
        if "\n" not in widget.text and text_width(widget.text, FONT_SIZES["med"]) * FIT_SAFE <= box_w:
            return "med"
        return "small"
    if widget.vertical:
        return "med" if item.w >= 96 else "small"
    pad_x, gap = _centered_geometry(item)
    box_w = max(8.0, item.w - 2 * pad_x - ((_visual_width(item) + gap) if has_visual else 0))
    if item.h < 42 or item.w < 64:
        return "small" if text_width(widget.text, FONT_SIZES["med"]) * FIT_SAFE > box_w else "med"
    for cand in ("normal", "med"):
        if text_width(widget.text, FONT_SIZES[cand]) * FIT_SAFE <= box_w:
            return cand
    return "small"


def button_sub_text_size(item, box_w):
    """Font size for main text in a button with `sub`; fits compact tiles cleanly."""
    widget = item.widget
    if text_width(widget.text, FONT_SIZES["med"]) * 1.0 > box_w - FIT_SLACK:
        return "small"
    return "med"


def _text_room(item):
    """Widest single line the label of this button may use."""
    widget = item.widget
    if widget.swatch is not None:
        return 0.0
    has_visual = bool(widget.icon) or widget.dot is not None
    if not has_visual:
        pad_x = (8 if item.w < 145 else 14) if widget.align == "left" else (2 if widget.kind == "kbd" else 4)
        if widget.align == "left":
            return float(max(8, item.w - pad_x - _left_geometry(item)[2]))
        return float(max(8, item.w - 2 * pad_x))
    if not widget.text:
        return 0.0
    if widget.vertical:
        return float(item.w - 4)
    visual = _visual_width(item)
    if widget.align == "left":
        left_pad, gap, pad_r = _left_geometry(item)
        return float(max(8, item.w - left_pad - visual - gap - pad_r))
    pad_x, gap = _centered_geometry(item)
    return float(max(8.0, item.w - 2 * pad_x - visual - gap))


_SHRINK = ("hero", "huge", "num", "big", "h2", "normal", "med", "small", "tab")


def button_label(item):
    """(size, text) the renderers draw for a button: one line, never broken inside a word.

    Starts from the nominal size, steps down while the text does not fit its box, and only when even
    the smallest size is too wide cuts the text with an ellipsis.  Text with an explicit newline is left alone.
    """
    widget = item.widget
    size = _nominal_size(item)
    text = widget.text
    room = _text_room(item)
    if not text or room <= 0 or "\n" in text:
        return size, text
    start = _SHRINK.index(size) if size in _SHRINK else _SHRINK.index("small")
    floor = _SHRINK.index("tab") if size == "tab" else _SHRINK.index("small")
    candidates = _SHRINK[start:max(floor, start) + 1]
    for name in candidates:  # comfortable fit first, even at a smaller size
        if text_width(text, FONT_SIZES[name]) * FIT_SAFE <= room:
            return name, text
    for name in candidates:  # then a tight single line
        if text_width(text, FONT_SIZES[name]) + FIT_SLACK <= room:
            return name, text
    last = candidates[-1]
    return last, ellipsize(text, FONT_SIZES[last], room - FIT_SLACK)


def button_sub_label(item, box_w):
    """(main size, main text, sub text) of a two-line button, each cut to `box_w` if needed."""
    widget = item.widget
    size = button_sub_text_size(item, box_w)
    main = widget.text
    if text_width(main, FONT_SIZES[size]) + FIT_SLACK > box_w:
        main = ellipsize(main, FONT_SIZES[size], box_w - FIT_SLACK)
    sub = widget.sub
    if text_width(sub, FONT_SIZES["small"]) + FIT_SLACK > box_w:
        sub = ellipsize(sub, FONT_SIZES["small"], box_w - FIT_SLACK)
    return size, main, sub


def button_radius(widget):
    if widget.kind == "card":
        return 12
    if widget.kind in ("segment", "segment_off") or widget.swatch is not None:
        return 8
    return 10


def button_fill(widget):
    if widget.swatch is not None:
        return widget.swatch
    if widget.kind in ("ghost", "tab", "tab_active", "estop"):
        return None
    if widget.action is None:
        return "card" if widget.kind == "card" else "disabled"
    return {
        "normal": "button",
        "primary": "primary",
        "danger": "danger",
        "outline_danger": "danger_bg",
        "active": "active",
        "segment": "surface4",
        "segment_off": "surface2",
        "key": "surface4",
        "kbd": "surface4",
        "card": "card",
    }.get(widget.kind, "button")


def button_border(widget):
    if widget.swatch is not None:
        return "text" if widget.ring else "border_strong"
    if widget.kind in ("ghost", "tab", "tab_active", "primary", "danger", "segment_off", "estop"):
        return None
    if widget.action is None:
        return "border_subtle" if widget.kind in ("normal", "card", "outline_danger") else None
    return {
        "normal": "border_default",
        "outline_danger": "danger_border",
        "active": "accent",
        "segment": "border_strong",
        "key": "border_strong",
        "kbd": "border_strong",
        "card": "border_subtle",
    }.get(widget.kind)


def button_border_width(widget):
    return 2 if widget.swatch is not None and widget.ring else 1


def swatch_check_color(rgb):
    return "on_accent" if (0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2]) > 140 else "text"


def button_text_color(widget):
    if widget.kind == "tab_active":
        return "text"
    if widget.kind == "tab":
        return "tertiary"
    if widget.action is None and widget.kind != "ghost":
        return "disabled_text"
    if widget.action is None and widget.kind == "ghost":
        return "disabled_text" if widget.dot is None else "text"
    return {
        "primary": "on_accent",
        "danger": "on_danger",
        "outline_danger": "danger_text",
        "active": "active_text",
        "segment_off": "muted",
        "ghost": "muted",
    }.get(widget.kind, "text")


def button_icon_color(widget):
    if widget.icon_color and (widget.action is not None or widget.kind == "ghost"):
        return widget.icon_color
    if widget.kind == "tab_active":
        return "accent"
    if widget.kind == "tab":
        return "tertiary"
    if widget.action is None and widget.kind != "ghost":
        return "disabled_text"
    if widget.action is None and widget.kind == "ghost":
        return "disabled_text"
    return {
        "primary": "on_accent",
        "danger": "on_danger",
        "outline_danger": "danger_text",
        "active": "active_icon",
        "card": "muted",
        "ghost": "muted",
        "estop": "text",
    }.get(widget.kind, "text")


def button_parts(item):
    """Where a button's icon/dot and text go: (visual centre or None, text box or None).

    Both renderers use this so the preview matches the printer.
    """
    widget = item.widget
    if widget.swatch is not None:
        return None, None
    has_visual = bool(widget.icon) or widget.dot is not None
    compact_left = (widget.align == "left" and item.w < 145)
    pad_r = (52 if widget.toggle is not None else 28 if widget.right_icon else 6) if compact_left else (
        56 if widget.toggle is not None else 32 if widget.right_icon else 12)
    if not has_visual:
        pad_x = (8 if compact_left else 14) if widget.align == "left" else (2 if widget.kind == "kbd" else 4)
        right = pad_r if widget.align == "left" else pad_x
        return None, (item.x + pad_x, item.y, max(8, item.w - pad_x - right), item.h)
    if widget.dot is not None:
        visual = button_dot_radius(item) * 2.0
    else:
        visual = ICON_SIZES[button_icon_size(item)]
    if not widget.text:
        return (item.x + item.w / 2.0, item.y + item.h / 2.0), None
    if widget.vertical:
        label_size = button_label(item)[0]
        text_h = int(round(FONT_SIZES[label_size] * 1.6)) + 1
        gap = 4 if widget.kind in ("tab", "tab_active") else 8
        top_bias = 3 if widget.kind == "tab_active" else 0
        top = item.y + top_bias + (item.h - top_bias - visual - gap - text_h) / 2.0
        return (item.x + item.w / 2.0, top + visual / 2.0), (item.x + 2, top + visual + gap, item.w - 4, text_h)
    if widget.align == "left":
        left_pad = 8 if compact_left else 14
        gap = 6 if compact_left else 10
        return ((item.x + left_pad + visual / 2.0, item.y + item.h / 2.0),
                (item.x + left_pad + visual + gap, item.y, max(8, item.w - left_pad - visual - gap - pad_r), item.h))
    pad_x, gap = _centered_geometry(item)
    label_size, label_text = button_label(item)[:2]
    tw = text_width(label_text, FONT_SIZES[label_size])
    max_text_w = max(8.0, item.w - 2 * pad_x - visual - gap)
    text_w = min(max_text_w, tw * FIT_SAFE + 8.0)
    start_x = item.x + (item.w - (visual + gap + text_w)) / 2.0
    return ((start_x + visual / 2.0, item.y + item.h / 2.0),
            (start_x + visual + gap, item.y, text_w, item.h))
