"""Toolkit-neutral widgets and the layout that places them on the 272x480 panel.

Screens return a list of Row and Card elements.  `place()` turns that into
absolutely positioned widgets, which the LVGL renderer (printer) and the PIL
renderer (PC preview, tests) both draw.
"""

from dataclasses import dataclass
from functools import lru_cache
import math

from . import font_metrics as _fm
from .theme import FONT_SIZES, ICON_SIZES

WIDTH, HEIGHT = 272, 480
TITLE_H, TABS_H, MARGIN, GAP, PAD = 44, 64, 12, 8, 12
DOT_SIZE = 32

# Text is measured with the real advance widths of AlibabaSans-Regular.ttf (font_metrics.py, generated by
# gen_font_metrics.py from the same file the printer loads) so both renderers place icon+label pairs
# identically without needing PIL on the printer.
FIT_SAFE = 1.15  # comfortable fit: text * 1.15 fits the box
FIT_SLACK = 2    # tight fit: text + 2 px fits the box


@lru_cache(maxsize=4096)
def text_width(text, px):
    """Width in px of one line as LVGL TinyTTF lays it out (per-glyph rounded advances, no kerning).

    Takes the larger of the sum of rounded advances and the exact sum rounded to a pixel, so an off-by-one in the
    rasteriser never overflows.
    """
    scale = px / float(_fm.UNITS_PER_EM)
    exact = 0.0
    rounded = 0
    for ch in text:
        if ch == "\n":
            continue
        units = _fm.ADVANCES.get(ch, _fm.DEFAULT_ADVANCE)
        exact += units * scale
        rounded += int(math.floor(units * scale + 0.5))
    return float(max(rounded, int(math.floor(exact + 0.5))))


approx_text_width = text_width  # historical name


def font_line_height(px):
    return int(math.floor((_fm.ASCENT - _fm.DESCENT + _fm.LINE_GAP) * px / float(_fm.UNITS_PER_EM) + 0.5))


def ellipsize(text, px, max_w):
    """Cut `text` so it fits `max_w` on one line, ending in an ellipsis (never mid-word if a word boundary fits)."""
    if text_width(text, px) <= max_w:
        return text
    ell = "\u2026" if "\u2026" in _fm.ADVANCES else "..."
    cut = len(text)
    while cut > 0 and text_width(text[:cut].rstrip() + ell, px) > max_w:
        cut -= 1
    # Prefer a word boundary when it keeps at least half of what fits.
    head = text[:cut].rstrip()
    space = head.rfind(" ")
    if space >= max(2, len(head) // 2):
        head = head[:space].rstrip()
    return head + ell if head else ell


